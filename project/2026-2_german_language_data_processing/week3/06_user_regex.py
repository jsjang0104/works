# ============================================================
# 예제 7. 금액 추출  (독일식 숫자)
# ============================================================
# 독일어권에서는 천 단위에 점(.), 소수에 쉼표(,)를 씁니다.
#   1.000,50 €   =  한국어의 1,000.50원과 같은 느낌
#
# 패턴을 조각으로 보면:
#   \b                 단어가 여기서 시작
#   \d{1,3}            맨 앞 숫자 1~3자리     (1  또는 12  또는 123)
#   (?:\.\d{3})*       .000 처럼 ". + 숫자3개"가 0번 이상 반복
#                      ?: 는 "찾되, 따로 저장하지는 않음"(비캡처 그룹)
#   ,\d{2}             쉼표 + 소수 2자리      (,50)
#   \s?€               공백은 있어도 되고 없어도 됨 + 유로 기호

text = "Der Termin ist am 17.06.2024. Die Rechnung beträgt 1.000,50 €."
money_pattern = r"\b\d{1,3}(?:\.\d{3})*,\d{2}\s?€"
#print("금액 추출:", re.findall(money_pattern, text))  # ['1.000,50 €']


