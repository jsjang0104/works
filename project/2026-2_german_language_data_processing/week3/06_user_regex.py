# [cb]at  →  첫 글자가 c 또는 b 이고, 뒤에 at
#   cat, bat 는 맞고  hat 은 안 맞음 (h는 목록에 없음)
#
# 범위로 적을 수도 있습니다.
#   [a-z]  → 소문자 a부터 z까지
#   [0-9]  → 숫자 0부터 9까지  (\d 와 같음)
#   [A-Z]  → 대문자 A부터 Z까지

text = "cat bat hat"
#print(re.findall(r"[cb]at", text))  # ['cat', 'bat']

"소문자만 찾는다."
#re.findall(r"[a-z]", "ABCabc123")  # ['a', 'b', 'c']

"숫자만 찾는다."
#re.findall(r"[0-9]", "abc123")  # ['1', '2', '3']


# ============================================================
# re.match()  : 문자열 맨 앞에서만 찾기
# ============================================================
