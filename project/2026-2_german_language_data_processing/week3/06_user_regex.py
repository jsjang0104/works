# ============================================================
# ^  : 문자열의 시작
# ============================================================
# ^ 는 "맨 앞에서 시작해야 한다"는 뜻입니다.
# "^Python"  → 문자열이 Python으로 시작하는지 확인
# 중간에 있는 Python은 찾지 않습니다.

text = "Python is easy"
#print(re.search(r"^Python", text))  # 맨 앞이 Python이면 Match 객체


# ============================================================
# $  : 문자열의 끝
# ============================================================
# $ 는 "맨 끝에서 끝나야 한다"는 뜻입니다.
# "Python$"  → 문자열이 Python으로 끝나는지 확인

text = "I love Python"
#print(re.search(r"Python$", text))  # 맨 끝이 Python이면 Match 객체


# ============================================================
# []  : 문자 집합 (이 칸에 들어올 수 있는 글자들을 나열)
