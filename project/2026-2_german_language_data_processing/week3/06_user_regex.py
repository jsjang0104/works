# 예제 8. 태그 안 내용 추출
# ============================================================
# HTML에서 <p>와 </p> 사이에 있는 글자만 꺼내고 싶을 때 씁니다.
#
# <p>(.*?)</p>
#   <p>     시작 태그 그대로
#   ( ... ) 괄호는 "이 부분을 따로 기억해 달라"는 뜻 (캡처 그룹)
#   .       아무 글자 1개
#   *       0번 이상
#   ?       욕심을 줄임 (lazy).  처음 나오는 </p>에서 멈춤
#           ?가 없으면 마지막 </p>까지 한 번에 삼킬 수 있습니다.
# findall()은 캡처 그룹이 있으면 그 괄호 안 내용만 리스트로 줍니다.

text = "<p>안녕하세요</p><p>반갑습니다</p>"
#print(re.findall(r"<p>(.*?)</p>", text))  # ['안녕하세요', '반갑습니다']


