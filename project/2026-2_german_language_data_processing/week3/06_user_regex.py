"""
Python 정규 표현식 (regular expression, 줄여서 regex)

정규 표현식은 "글자의 패턴"을 적어 두고,
그 패턴과 맞는 부분을 찾거나, 바꾸거나, 잘라 내는 도구입니다.

비유:
    일반 검색   = "Python"처럼 글자를 그대로 찾기
    정규 표현식 = "숫자 4자리", "이메일처럼 생긴 것"처럼
                   모양이 비슷한 것들을 한꺼번에 찾기

왜 쓰나요?
    독일어 텍스트에서도 날짜(17.06.2024), 금액(1.000,50 €),
    이메일, 전화번호처럼 "형식이 정해진 정보"를 자주 뽑습니다.
    글자 하나하나를 if로 검사하는 것보다, 패턴 한 줄이 더 간단합니다.

자주 쓰는 함수 (re 모듈):
    re.search()  → 문자열 안에서 패턴이 처음 나오는 곳을 찾음
    re.match()   → 문자열의 "맨 앞"에서만 찾음
    re.findall() → 맞는 부분을 모두 모아 리스트로 줌
    re.sub()     → 찾은 부분을 다른 글자로 바꿈
    re.split()   → 패턴을 기준으로 문자열을 나눔

r"..." 표기 (raw string, 날것 문자열):
    정규식에서 \d, \w처럼 백슬래시(\)를 많이 씁니다.
    앞에 r을 붙이면 파이썬이 \를 특수 문자로 해석하지 않습니다.
    그래서 정규식 패턴은 보통 r"..." 로 적습니다.

아래 예제는 결과를 바로 보지 않도록 print() 앞에 # 을 달아 두었습니다.
실행하고 싶은 줄만 # 을 지우고 돌려 보세요.
"""
import re  # 정규 표현식을 쓰려면 표준 모듈 re를 불러옵니다.


# ============================================================
# 문자 그대로 찾기
# ============================================================
# 패턴에 특수 기호를 쓰지 않으면, 그 글자 그대로를 찾습니다.
# re.search(패턴, 문자열) : 처음 맞는 위치를 찾습니다.
# 찾으면 Match 객체를, 못 찾으면 None을 돌려줍니다.

text = "Python is fun"
result = re.search("Python", text)  # "Python"이 있으면 Match 객체
#print(result)


# ============================================================
# .  : 아무 문자 1개
# ============================================================
# 점(.)은 "무엇이든 글자 하나"를 뜻합니다.
# "c.t"  →  c + (아무 글자 1개) + t
# 그래서 cat, cut, cot가 모두 맞습니다.
# (줄바꿈 문자는 기본적으로 제외됩니다.)

text = "cat cut cot"
#print(re.findall("c.t", text))  # ['cat', 'cut', 'cot']


# ============================================================
# \d  : 숫자 1개
# ============================================================
# \d 는 digit(숫자)의 줄임말입니다.
# 0부터 9까지 숫자 한 글자와 같습니다.  [0-9] 와 같은 뜻입니다.
# 아래는 숫자 "한 개씩" 따로 찾습니다.  1234 → ['1', '2', '3', '4']
# 여러 자리를 한 덩어리로 찾으려면 뒤에서 배울 + 나 {} 를 붙입니다.

text = "내 번호는 1234입니다."
#print(re.findall(r"\d", text))  # ['1', '2', '3', '4']


# ============================================================
# \w  : 문자 / 숫자 / 밑줄 1개
# ============================================================
# \w 는 word(단어 구성 글자)의 줄임말입니다.
# 영문, 숫자, 밑줄(_) 한 글자입니다.  한글도 포함됩니다.
# 느낌표(!) 같은 문장 부호는 해당하지 않습니다.

text = "abc_123!"
#print(re.findall(r"\w", text))  # ['a', 'b', 'c', '_', '1', '2', '3']  (! 는 제외)


# ============================================================
# \s  : 공백 1개
# ============================================================
# \s 는 space(공백)의 줄임말입니다.
# 스페이스, 탭(\t), 줄바꿈(\n)처럼 "빈칸으로 보이는 것"을 가리킵니다.

text = "a b\tc\nd"  # 스페이스, 탭, 줄바꿈이 섞여 있습니다.
#print(re.findall(r"\s", text))  # 공백 문자 3개를 찾음


# ============================================================
# *  : 바로 앞 패턴이 0번 이상 반복
# ============================================================
# * 는 "없어도 되고, 여러 번 있어도 된다"는 뜻입니다.
# "ab*"  →  a 뒤에 b가 0번, 1번, 2번... 이어져도 됨
#   "a"    → a  (b가 0번)
#   "ab"   → ab (b가 1번)
#   "abb"  → abb
# "a"만 있어도 맞으므로, 목록에 'a'도 들어갑니다.

#print(re.findall(r"ab*", "a ab abb abbb"))  # ['a', 'ab', 'abb', 'abbb']


# ============================================================
# +  : 바로 앞 패턴이 1번 이상 반복
# ============================================================
# + 는 "적어도 한 번은 있어야 한다"는 뜻입니다.
# "ab+"  →  a 뒤에 b가 1번 이상
#   "a"    → 안 맞음  (b가 없음)
#   "ab"   → 맞음
# * 와 + 의 차이: * 는 0번도 허용, + 는 최소 1번 필요

#print(re.findall(r"ab+", "a ab abb abbb"))  # ['ab', 'abb', 'abbb']  ("a"는 제외)


# ============================================================
# ?  : 바로 앞 패턴이 0번 또는 1번
# ============================================================
# ? 는 "있어도 되고 없어도 된다" (단, 많아 봐야 1번)입니다.
# 영어 color / colour 처럼 철자가 둘 다 가능할 때 자주 씁니다.
# "colou?r"  →  u가 없거나(color), 한 번 있거나(colour)

#print(re.findall(r"colou?r", "color colour"))  # ['color', 'colour']


# ============================================================
# {n}  : 바로 앞 패턴을 정확히 n번
# ============================================================
# {4} 는 "바로 앞 것이 정확히 4번"입니다.
# \d{4}  → 숫자 4자리  (연도 2024, 우편번호처럼 자릿수가 정해진 경우)
# 비슷한 표기:
#   {3,4}  → 3번 이상 4번 이하
#   {2,}   → 2번 이상

