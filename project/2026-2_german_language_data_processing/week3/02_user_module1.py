# ============================================================
# 더하기 / 빼기 함수
# ============================================================
# def : 함수를 만들 때 쓰는 키워드
# a, b : 함수가 받을 두 숫자 (매개변수)
# return : 계산 결과를 호출한 곳으로 돌려줌


def add(a, b):
    # 두 숫자를 더한 값을 돌려줍니다.
    # 예: add(10, 5) → 15
    return a + b


def sub(a, b):
    # 첫 번째 숫자에서 두 번째 숫자를 뺀 값을 돌려줍니다.
    # 예: sub(10, 5) → 5
    return a - b
