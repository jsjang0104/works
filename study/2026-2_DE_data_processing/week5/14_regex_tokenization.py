# ==========================================================
# 정규표현식을 이용한 단어 분리
#
# 13번의 split()은 문장부호를 단어에 붙여 둡니다.
# 여기서는 "독일어 글자의 덩어리"와 "문장부호"를 따로 찾아
# 더 정교하게 토큰을 만듭니다.
#
# 기능:
# 1. 정규표현식으로 독일어 단어와 문장부호를 분리한다.
# 2. Umlaut(ä, ö, ü)와 ß를 포함한 단어를 고려한다.
# 3. 공백 기반 분리보다 더 정교한 토큰화 예시를 제공한다.
#
# 용어 안내:
# - re.findall(): 패턴에 맞는 부분을 모두 찾아 리스트로 반환
# - [A-Za-z]+ : 영어 알파벳이 1글자 이상 이어진 것
# ==========================================================

import re


sample_sentence = "„Deutschland ist groß“, sagte er über die Straße."

print("=== 원문 문장 ===")
print(sample_sentence)

# ----------------------------------------------------------
# 독일어 단어(ASCII + Umlaut + ß)와 문장부호를 각각 토큰으로 추출
#
# [A-Za-zÄÖÜäöüß]+  : 영어 알파벳 + 독일어 특수문자가 이어진 단어
# |                 : 또는
# [.,!?„“\"():;-]   : 문장부호 1글자
#
# 공백은 패턴에 없으므로 자동으로 건너뜁니다.
# ----------------------------------------------------------
pattern = r"[A-Za-zÄÖÜäöüß]+|[.,!?„“\"():;-]"
regex_tokens = re.findall(pattern, sample_sentence)

print("\n=== 정규표현식 기반 토큰화 결과 ===")
for i, token in enumerate(regex_tokens, start=1):
    print(f"{i}. {token}")
