# ==========================================================
# 저장 결과 확인하기
#
# 06, 07번에서 만든 파일을 다시 열어 봅니다.
# "저장됐다"고 출력되어도, 실제로 글자가 깨졌을 수 있기 때문입니다.
#
# 기능:
# 1. 저장한 TXT 파일과 CSV 파일을 다시 읽는다.
# 2. 독일어 텍스트가 정상적으로 저장되었는지 확인한다.
# 3. 앞부분 일부를 출력하여 인코딩과 내용 상태를 점검한다.
#
# 이 파일은 인터넷에 접속하지 않습니다.
# 같은 폴더에 저장된 파일만 읽습니다.
# ==========================================================

import csv


# ==========================================================
# 1. TXT 파일 확인
#    앞에서 500글자만 읽어 움라우트(ä, ö, ü)와 ß가 보이는지 확인합니다.
# ==========================================================

txt_file = "german_webpage_text.txt"
print("=== TXT 파일 확인 ===")
try:
    with open(txt_file, "r", encoding="utf-8") as f:
        txt_preview = f.read(500)
    print(txt_preview)
except FileNotFoundError:
    # 06번 파일을 아직 실행하지 않았으면 이 메시지가 나옵니다.
    print(f"파일을 찾을 수 없습니다: {txt_file}")

print("\n" + "=" * 40 + "\n")


# ==========================================================
# 2. CSV 파일 확인
#    헤더 1줄 + 문단 5줄 = 앞에서 6줄을 미리 봅니다.
# ==========================================================

csv_file = "german_webpage_paragraphs.csv"
print("=== CSV 파일 확인 ===")
try:
    with open(csv_file, "r", encoding="utf-8-sig", newline="") as f:
        reader = csv.reader(f)
        rows = list(reader)  # 모든 행을 리스트로 가져옵니다.

    for row in rows[:6]:  # 헤더 포함 5개 행 미리보기
        print(row)
except FileNotFoundError:
    # 07번 파일을 아직 실행하지 않았으면 이 메시지가 나옵니다.
    print(f"파일을 찾을 수 없습니다: {csv_file}")
