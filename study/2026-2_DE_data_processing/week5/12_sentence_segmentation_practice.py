# ==========================================================
# 문장 분리 실습
#
# 긴 글을 분석하려면 먼저 "문장 하나"로 잘라야 합니다.
# 여기서는 마침표(.), 물음표(?), 느낌표(!) 뒤를 문장 끝으로 봅니다.
# 약어(z.B., Dr.)처럼 점이 문장 끝이 아닌 경우는 한계로 남습니다.
#
# 기능:
# 1. 독일어 예문을 문장 단위로 분리한다.
# 2. 마침표, 물음표, 느낌표를 기준으로 기본 분리를 수행한다.
# 3. 약어 등 실제 한계가 있음을 확인하는 출발점으로 사용한다.
#
# 용어 안내:
# - 문장 분리(sentence segmentation): 글을 문장 단위로 나누는 일
# - 정규표현식 뒤쪽 조건 (?<= ... ): "바로 앞에 이런 글자가 있을 때"
# ==========================================================

import re


sample_text = "Deutschland diskutiert heute über neue Regeln. Viele Bürger reagieren kritisch! Ist das wirklich sinnvoll?"

print("=== 원문 텍스트 ===")
print(sample_text)

# ----------------------------------------------------------
# 문장 끝 문장부호 뒤의 공백을 기준으로 분리
#
# (?<=[.!?])  : 바로 앞이 . 또는 ! 또는 ? 일 때
# \s+         : 그 뒤의 공백 1개 이상에서 자른다
#
# 이렇게 하면 문장부호는 문장 끝에 남고, 공백만 분리점이 됩니다.
# ----------------------------------------------------------
sentences = re.split(r'(?<=[.!?])\s+', sample_text)

print("\n=== 문장 분리 결과 ===")
for i, sentence in enumerate(sentences, start=1):
    print(f"{i}. {sentence}")
