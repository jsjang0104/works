# ==========================================================
# 공백 기반 문자열 분리
#
# 토큰화(tokenization)의 가장 단순한 방법입니다.
# 스페이스(빈칸)가 있는 곳마다 잘라 단어처럼 나눕니다.
#
# 기능:
# 1. 문장을 가장 단순한 방식으로 공백 기준 분리한다.
# 2. split() 결과를 통해 초급 문자열 처리의 원리를 이해한다.
# 3. 문장부호가 단어에 붙어 남는 한계를 관찰한다.
#
# 용어 안내:
# - 토큰(token): 분석 단위. 보통 단어, 문장부호 하나하나를 가리킴
# - split(): 기본값은 공백을 기준으로 문자열을 잘라 리스트로 만듦
# ==========================================================


# „ “ 는 독일어에서 자주 쓰는 따옴표입니다.
sample_sentence = "„Deutschland ist groß“, sagte er."

print("=== 원문 문장 ===")
print(sample_sentence)

# 공백 기준 분리
# 예: "groß“," 처럼 따옴표·쉼표가 단어에 붙어 남을 수 있습니다.
tokens = sample_sentence.split()

print("\n=== 공백 기반 분리 결과 ===")
for i, token in enumerate(tokens, start=1):
    print(f"{i}. {token}")
