# ==========================================================
# 줄바꿈, 공백, 불필요한 기호 정리
#
# 웹에서 가져온 글에는 빈 줄, 여러 칸 띄어쓰기, 광고성 기호가
# 섞여 있는 경우가 많습니다. 분석 전에 글을 "깨끗하게" 만듭니다.
#
# 기능:
# 1. 예시 독일어 텍스트에서 줄바꿈과 중복 공백을 정리한다.
# 2. 분석에 불필요한 일부 기호를 제거한다.
# 3. 정제 전후 결과를 비교한다.
#
# 용어 안내:
# - 정규표현식(re): "이런 모양의 글자를 찾아라"고 패턴으로 지시하는 방법
# - \s: 공백, 탭, 줄바꿈처럼 "빈칸으로 보이는 것"을 통틀어 가리킴
# ==========================================================

import re  # 정규표현식 모듈


sample_text = """
Deutschland   diskutiert heute   über neue Regeln. 

Mehr  dazu   lesen Sie   auch!!!
>>> Jetzt abonnieren!!!
"""

print("=== 정제 전 텍스트 ===")
print(sample_text)

# ----------------------------------------------------------
# 1. 줄바꿈을 공백으로 치환
#    \n 은 "줄을 바꾸라"는 특수 문자입니다.
# ----------------------------------------------------------
cleaned = sample_text.replace("\n", " ")

# ----------------------------------------------------------
# 2. 불필요한 기호 일부 제거 (>, ! 등 예시)
#    [>!]+ : > 또는 ! 가 하나 이상 연속된 부분을 찾습니다.
#    빈 문자열 "" 로 바꿔서 지웁니다.
# ----------------------------------------------------------
cleaned = re.sub(r"[>!]+", "", cleaned)

# ----------------------------------------------------------
# 3. 중복 공백 정리
#    \s+ : 공백이 1개 이상이 연속되면
#    하나의 스페이스(" ")로 바꿉니다.
#    strip(): 맨 앞과 맨 뒤의 남는 공백을 제거합니다.
# ----------------------------------------------------------
cleaned = re.sub(r"\s+", " ", cleaned).strip()

print("\n=== 정제 후 텍스트 ===")
print(cleaned)
