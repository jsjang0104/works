"""04. Word2Vec: 문맥으로부터 단어 임베딩 학습"""
# 필요 패키지 설치: pip install gensim
from gensim.models import Word2Vec

# ------------------------------------------------------------
# 1) 학습용 말뭉치(corpus) 준비
#    - Word2Vec은 "문장 전체"가 아니라 "단어 리스트"를 입력으로 받습니다.
#    - 예: "das haus ist groß" → ["das", "haus", "ist", "groß"]
#    - 아래 문장들은 'haus', 'wohnung', 'gebäude'처럼
#      비슷한 의미의 단어가 비슷한 문맥(ist groß, hat einen ...)에
#      나타나도록 구성한 작은 예시입니다.
# ------------------------------------------------------------
sentences = [
    ["das", "haus", "ist", "groß"],           # 그 집은 크다
    ["das", "haus", "hat", "einen", "garten"], # 그 집은 정원이 있다
    ["die", "wohnung", "ist", "groß"],         # 그 아파트는 크다
    ["die", "wohnung", "hat", "einen", "balkon"],  # 그 아파트는 발코니가 있다
    ["das", "gebäude", "ist", "alt"],          # 그 건물은 오래되었다
]

# ------------------------------------------------------------
# 2) Word2Vec 모델 학습
#    아이디어(분포 가설):
#      "비슷한 문맥에 나타나는 단어는 비슷한 의미를 가진다."
#    예) haus / wohnung 둘 다 "ist groß", "hat einen ..." 근처에 자주 나옴
#
#    주요 하이퍼파라미터(설정값):
#      vector_size=20 : 각 단어를 20개 숫자(20차원 벡터)로 표현
#      window=2       : 중심 단어의 좌우 각 2개 단어를 문맥으로 봄
#      min_count=1    : 1번만 나온 단어도 학습에 포함 (작은 예제용)
#      workers=1      : 학습에 사용할 CPU 스레드 수 (1이면 결과 재현이 쉬움)
#      epochs=200     : 전체 말뭉치를 200번 반복 학습 (데이터가 작아 횟수를 늘림)
#      seed=42        : 난수를 고정해 실행할 때마다 비슷한 결과가 나오게 함
# ------------------------------------------------------------
model = Word2Vec(
    sentences,
    vector_size=20,
    window=2,
    min_count=1,
    workers=1,
    epochs=200,
    seed=42,
)

# ------------------------------------------------------------
# 3) 학습 결과 확인
#    model.wv : 학습된 단어 벡터 사전
#
#    most_similar('haus', topn=3)
#      → 'haus'와 코사인 유사도가 높은 단어 3개 출력
#      → 형식: [('단어', 유사도), ...]
#
#    주의:
#      말뭉치가 매우 작아서 결과는 "원리 시연용"입니다.
#      실제 대규모 데이터처럼 완벽한 의미 유사도를 보장하지는 않습니다.
# ------------------------------------------------------------
print("haus와 비슷한 단어:")
print(model.wv.most_similar("haus", topn=3))

# model.wv['haus'] : 'haus'의 20차원 벡터 전체
# [:5]             : 앞의 숫자 5개만 출력해 벡터 형태를 확인
print("haus 벡터의 앞 5개 값:")
print(model.wv["haus"][:5])
