"""
Python 내장 함수

내장 함수(built-in function)는 파이썬을 설치하면 처음부터 들어 있는 함수입니다.
import로 모듈을 불러오지 않아도, 이름만 적으면 바로 사용할 수 있습니다.

비유:
    내장 함수 = 주방에 처음부터 놓여 있는 기본 도구
               (칼, 도마처럼 따로 사지 않아도 바로 씀)
    모듈 함수 = 필요할 때 꺼내 쓰는 전용 도구
               (math.sqrt처럼 import 한 뒤에 씀)

자주 쓰는 내장 함수 예시:
    int, float, str  → 값의 종류(타입)를 바꿈
    len              → 길이(개수)를 셈
    sum, max, min    → 합계, 최댓값, 최솟값
    sorted, reversed → 정렬, 역순
    enumerate, zip  → 여러 값을 함께 순회

아래 예제들은 연습용으로 삼중 따옴표로 감싸 두었습니다.
실행하고 싶은 부분만 삼중 따옴표를 지우고 돌려 보세요.
"""

# ============================================================
# int(), float(), str()  — 형변환 (타입을 바꾸기)
# ============================================================
# 형변환: 값의 "종류"를 다른 종류로 바꾸는 일입니다.
#
#   int()   : 정수(소수점 없는 숫자)로 바꿈    예: "20" → 20
#   float() : 실수(소수점 있는 숫자)로 바꿈    예: "175.5" → 175.5
#   str()   : 문자열(글자)로 바꿈              예: 95 → "95"
#
# input()의 결과는 항상 문자열입니다.
# "20"과 20은 겉모습은 비슷해도, 파이썬에게는 다른 종류입니다.
# 숫자 계산을 하려면 int()나 float()로 먼저 바꿔야 합니다.
#
# 문자열끼리만 + 로 이어 붙일 수 있습니다.
# 그래서 점수(숫자)를 문장에 넣을 때 str()이 필요합니다.

"""
age = int(input("나이: "))      # 입력받은 글자를 정수로 바꿈
height = float(input("키: "))   # 입력받은 글자를 실수로 바꿈
print("나이:", age)
print("키:", height)

score = 95
# str(score) : 95 → "95"  (글자로 바꿔야 문장과 + 로 이어 붙일 수 있음)
print("점수는 " + str(score) + "점입니다.")
"""

# ============================================================
# len()  — 길이 구하기
# ============================================================
# len()은 "안에 들어 있는 것이 몇 개인가?"를 알려 줍니다.
#   문자열 → 글자 수
#   리스트 → 칸(원소) 개수
#
# 독일어 텍스트를 다룰 때도 단어 길이, 문장 길이 등을 셀 때 자주 씁니다.

"""
word = "Python"
print(len(word))   # 6  ("P","y","t","h","o","n" → 글자 6개)

numbers = [10, 20, 30]
print(len(numbers))   # 3  (리스트 칸이 3개)
"""

# ============================================================
# sum(), max(), min()  — 기초 집계 함수
# ============================================================
# 여러 숫자를 한 번에 살펴볼 때 씁니다.
#   sum() : 모두 더함
#   max() : 가장 큰 값
#   min() : 가장 작은 값
#
# 시험 점수 리스트가 있을 때
#   총점, 최고점, 최저점을 바로 구할 수 있습니다.

"""
scores = [80, 90, 75, 100]

print(sum(scores))   # 345  (80+90+75+100)
print(max(scores))   # 100  (가장 높은 점수)
print(min(scores))   # 75   (가장 낮은 점수)
"""

# ============================================================
# round()  — 반올림
# ============================================================
# round(숫자)      : 가장 가까운 정수로 반올림
# round(숫자, 자리) : 소수점 아래 몇 자리까지 남길지 정함
#
# 예:
#   round(3.141592)     → 3
#   round(3.141592, 2)  → 3.14   (소수점 둘째 자리까지)

"""
pi = 3.141592
print(round(pi))      # 3
print(round(pi, 2))   # 3.14
"""

# ============================================================
# range()  — 반복 범위 생성
# ============================================================
# range()는 "이 숫자부터 저 숫자 직전까지"의 정수 묶음을 만듭니다.
# for 반복문과 함께 가장 많이 씁니다.
#
#   range(5)        → 0, 1, 2, 3, 4     (0부터 5 직전까지)
#   range(1, 6)     → 1, 2, 3, 4, 5     (1부터 6 직전까지)
#   range(0, 10, 2) → 0, 2, 4, 6, 8     (2씩 건너뛰며)
#
# 주의: 끝 숫자는 포함되지 않습니다. range(5)에 5는 없습니다.

"""
for i in range(5):
    print(i)   # 0 1 2 3 4  가 한 줄씩 출력됩니다.
"""

# ============================================================
# list()  — 리스트로 변환
# ============================================================
# list()는 여러 값을 리스트 [ ] 형태로 바꿔 줍니다.
# range()나 문자열처럼 "하나씩 꺼낼 수 있는 것"을
# 눈으로 보기 쉬운 리스트로 만들 때 씁니다.
#
#   list(range(5)) → [0, 1, 2, 3, 4]
#   list("abc")    → ['a', 'b', 'c']  (글자 하나하나가 칸이 됨)

"""
print(list(range(5)))   # [0, 1, 2, 3, 4]
print(list("abc"))      # ['a', 'b', 'c']
"""

# ============================================================
# sorted()  — 정렬의 기초
# ============================================================
# sorted()는 작은 값부터 큰 값 순서로 새 리스트를 만들어 줍니다.
# 원래 리스트는 그대로 두고, "정렬된 복사본"을 반환합니다.
#
# 나중에 배울 sort()는 원본을 직접 바꾸지만,
# sorted()는 원본을 건드리지 않습니다.

"""
numbers = [3, 1, 4, 2]
print(sorted(numbers))   # [1, 2, 3, 4]
# print(numbers)         # [3, 1, 4, 2]  ← 원본은 그대로
"""

# ============================================================
# enumerate()  — 인덱스와 값을 함께 다루기
# ============================================================
# 리스트를 for로 돌리면 값만 나옵니다.
# 그런데 "몇 번째 칸의 무슨 값"인지 함께 알고 싶을 때가 있습니다.
#
# enumerate(리스트)는 (번호, 값) 쌍을 만들어 줍니다.
# 번호(인덱스)는 0부터 시작합니다.
#
#   fruits = ["apple", "banana", "cherry"]
#   0 apple
#   1 banana
#   2 cherry

"""
fruits = ["apple", "banana", "cherry"]
for i, fruit in enumerate(fruits):
    # i     : 칸 번호 (0, 1, 2)
    # fruit : 그 칸의 값
    print(i, fruit)
"""

# ============================================================
# zip()  — 여러 시퀀스를 동시에 순회
# ============================================================
# zip()은 같은 위치의 값끼리 짝을 지어 줍니다.
# 이름 리스트와 점수 리스트가 따로 있을 때,
# "Anna는 90점"처럼 한 사람씩 묶어 처리할 수 있습니다.
#
#   names  = ["Anna", "Tom", "Mina"]
#   scores = [90,     85,    100]
#            ----------------------
#   1번째 짝: Anna, 90
#   2번째 짝: Tom,  85
#   3번째 짝: Mina, 100
#
# 길이가 다르면 더 짧은 쪽까지만 짝을 만듭니다.

"""
names = ["Anna", "Tom", "Mina"]
scores = [90, 85, 100]

for name, score in zip(names, scores):
    print(name, score)
"""

# ============================================================
# map()  — 일괄 변환
# ============================================================
# map(함수, 리스트)는 리스트의 각 값에 같은 함수를 적용합니다.
# "하나씩 꺼내서 바꾸고, 다시 모아 두기"를 한 줄로 하는 도구입니다.
#
# 예: 문자열 숫자 ["1", "2", "3"]을 진짜 숫자 [1, 2, 3]으로 바꾸기
#   map(int, numbers)  → int("1"), int("2"), int("3")
#
# map()의 결과는 바로 print 해도 리스트처럼 보이지 않습니다.
# 그래서 보통 list()로 한 번 더 감싸서 확인합니다.

"""
numbers = ["1", "2", "3"]          # 지금은 모두 문자열
result = list(map(int, numbers))    # 각 칸에 int()를 적용
print(result)                      # [1, 2, 3]
"""

# ============================================================
# sorted()의 중급 활용 — key
# ============================================================
# key는 "무엇을 기준으로 정렬할 것인가?"를 지정하는 옵션입니다.
#
# 기본 sorted(단어들)  → 알파벳(가나다) 순
# key=len 을 주면     → 글자 수를 기준으로 정렬
#
# 독일어 단어 목록을 "짧은 단어부터" 보고 싶을 때 유용합니다.

# --- 예시 1: 문자열 길이 기준 정렬 ---
"""
words = ["Haus", "Bibliothek", "Buch", "Auto"]
print(sorted(words, key=len))
# 글자 수: Haus(4), Bibliothek(10), Buch(4), Auto(4)
# 같은 길이끼리는 원래 순서를 유지하는 경우가 많습니다.
# 결과 예: ['Haus', 'Buch', 'Auto', 'Bibliothek']
"""

# --- 예시 2: 딕셔너리 리스트 정렬 ---
# 학생 정보가 {"이름": ..., "점수": ...} 형태로 여러 개 있을 때,
# 점수(score)를 기준으로 높은 사람부터 줄을 세울 수 있습니다.
#
# lambda x: x["score"]
#   → "각 학생 x에서 score 값을 꺼내 그 숫자로 비교하라"는 짧은 함수
# reverse=True
#   → 큰 값이 앞으로 오도록 내림차순 정렬 (기본은 오름차순)

"""
students = [
    {"name": "Anna", "score": 90},
    {"name": "Tom", "score": 85},
    {"name": "Mina", "score": 100}
]
result = sorted(students, key=lambda x: x["score"], reverse=True)
print(result)
# Mina(100) → Anna(90) → Tom(85) 순서로 정렬됩니다.
"""

# ============================================================
# reversed()  — 역순 처리
# ============================================================
# reversed()는 앞뒤를 뒤집어 줍니다.
#   [1, 2, 3, 4] → 4, 3, 2, 1
#
# sorted()와 마찬가지로, 결과를 보려면 보통 list()로 감쌉니다.
# 원래 리스트는 바뀌지 않습니다.

"""
numbers = [1, 2, 3, 4]
print(list(reversed(numbers)))   # [4, 3, 2, 1]
"""

# ============================================================
# any()와 all()  — 조건 집계
# ============================================================
# 여러 조건을 한꺼번에 확인할 때 씁니다.
#
#   all() : 모두가 참이어야 True
#           "전부 60점 이상인가?"
#   any() : 하나라도 참이면 True
#           "만점자가 한 명이라도 있는가?"
#
# 괄호 안의
#   score >= 60 for score in scores
# 는 "점수를 하나씩 꺼내 60 이상인지 검사한다"는 뜻입니다.
# (이런 한 줄 반복을 제너레이터 표현식이라고 합니다.)

"""
scores = [80, 90, 75]
print(all(score >= 60 for score in scores))   # True  (모두 60 이상)
print(any(score == 100 for score in scores))  # False (100점은 없음)
"""
