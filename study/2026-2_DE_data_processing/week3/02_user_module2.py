# ============================================================
# 모듈에 들어 있는 변수
# ============================================================
# 원주율처럼 여러 곳에서 쓰는 값을 모듈에 한 번만 적어 두면,
# 다른 파일에서도 같은 값을 그대로 가져다 쓸 수 있습니다.

PI = 3.141592   # 원주율 (π)


# ============================================================
# 모듈에 들어 있는 클래스
# ============================================================
# Math는 원의 넓이를 구하는 간단한 계산기 설계도입니다.

class Math:
    # solv : 반지름 r을 받아서 원의 넓이를 계산합니다.
    #        공식: 넓이 = π × (반지름 × 반지름)
    # self : 이 객체 자신 (클래스 안 함수의 첫 매개변수)
    def solv(self, r):
        # r ** 2 는 "r의 제곱" (r * r)과 같습니다.
        # 예: r이 2이면  3.141592 * (2 ** 2) = 12.566368
        return PI * (r ** 2)


# ============================================================
# 모듈에 들어 있는 함수
# ============================================================

def add(a, b):
    # 두 숫자를 더한 값을 돌려줍니다.
    # 예: add(3.141592, 10) → 13.141592
    return a + b
