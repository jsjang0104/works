"""
Python 모듈

모듈(module)은 함수, 변수, 클래스를 모아 둔 '.py 파일'입니다.
다른 파일에서 불러와 재사용할 수 있어서, 코드를 나눠 관리하기 좋습니다.

비유:
    모듈 = 요리 레시피 모음집
    import = 그 모음집을 펼쳐서 필요한 레시피를 쓰는 것

이 파일에서는 모듈을 불러오는 여러 방법을 살펴봅니다.
아래 1~4번은 연습용으로 삼중 따옴표로 감싸 두었습니다.
실행하고 싶은 부분만 삼중 따옴표를 지우고 돌려 보세요.
"""

# ============================================================
# 모듈 불러오기 1: 전체 모듈 불러오기
# ============================================================
# import 모듈이름
#   → 모듈 전체를 가져옵니다.
#   → 사용할 때: 모듈이름.함수이름()
#   장점: 어느 모듈의 함수인지 이름이 분명합니다.

"""
import user_module1

# user_module1 안에 있는 add, sub 함수를 호출합니다.
print(user_module1.add(10, 5))   # 15  (10 + 5)
print(user_module1.sub(10, 5))   # 5   (10 - 5)
"""

# ============================================================
# 모듈 불러오기 2: 모듈의 일부만 불러오기
# ============================================================
# from 모듈이름 import 이름1, 이름2
#   → 필요한 함수만 가져옵니다.
#   → 사용할 때: 함수이름()  (모듈 이름을 앞에 붙이지 않음)
#   장점: 코드가 짧아집니다.
#   주의: 같은 이름의 함수가 있으면 헷갈릴 수 있습니다.

"""
from user_module1 import add, sub

print(add(100, 50))   # 150  (100 + 50)
print(sub(100, 50))   # 50   (100 - 50)
"""

# ============================================================
# 모듈 불러오기 3: 별칭(alias) 사용하기
# ============================================================
# import 모듈이름 as 짧은이름
#   → 모듈에 별명을 붙입니다.
#   → 사용할 때: 짧은이름.함수이름()
#   장점: 모듈 이름이 길 때 타이핑이 줄어듭니다.

"""
import user_module1 as m1

# m1은 user_module1의 별명입니다.
print(m1.add(10, 5))   # 15
print(m1.sub(10, 5))   # 5
"""

# ============================================================
# 모듈 불러오기 4: 변수와 클래스가 들어 있는 모듈
# ============================================================
# 모듈에는 함수뿐 아니라 변수(PI)와 클래스(Math)도 들어 있을 수 있습니다.
# 점(.)으로 "모듈 안의 무엇"인지 지정합니다.

"""
import user_module2

print(user_module2.PI)              # 3.141592  (모듈에 저장된 원주율)

a = user_module2.Math()             # Math 클래스로 객체 a를 만듭니다.
print(a.solv(2))                    # 원의 넓이: π × 2²

print(user_module2.add(user_module2.PI, 10))  # 원주율 + 10
"""

# ============================================================
# 모듈 불러오기 5: 파이썬이 미리 제공하는 표준 모듈
# ============================================================
# 표준 모듈: 파이썬을 설치하면 처음부터 들어 있는 모듈
#            (직접 만들지 않아도 바로 import 할 수 있습니다.)
# math   : 제곱근, 원주율 등 수학 계산
# random : 난수(무작위 숫자) 만들기
#
# 아래 print 앞에 # 이 있으면 그 줄은 실행되지 않습니다.
# 실행해 보고 싶으면 # 을 지우고 파일을 다시 실행하세요.

# --- math: 수학 ---
import math
# print(math.sqrt(16))    # 16의 제곱근 → 4.0
                          # sqrt = square root (제곱근)

# from ... import ... 로 함수만 가져오면 math. 없이 바로 씁니다.
from math import sqrt
# print(sqrt(25))         # 25의 제곱근 → 5.0

# as 로 짧은 별명을 붙일 수도 있습니다.
import math as m
# print(m.pi)             # 파이썬 math 모듈에 들어 있는 원주율

# --- random: 무작위 숫자 ---
import random
# print(random.randint(1, 10))  # 1 이상 10 이하인 정수 하나를 무작위로 뽑습니다.
                                # randint = random integer (무작위 정수)
