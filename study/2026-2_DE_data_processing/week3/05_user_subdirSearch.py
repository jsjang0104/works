"""
Python 하위 디렉토리 검색하기

디렉토리(directory)는 폴더와 같은 말입니다.
하위 디렉토리 검색이란, 어떤 폴더 안뿐 아니라
그 안의 폴더, 또 그 안의 폴더까지 모두 살펴보는 일입니다.

비유:
    폴더     = 책장
    파일     = 책장 안에 꽂힌 책
    하위 폴더 = 책장 안의 작은 서랍
    rglob()  = "이 책장과 서랍 안까지 전부 뒤져 주세요"

pathlib 모듈:
    파일/폴더 경로를 다루기 위한 표준 도구입니다.
    Path("폴더이름") 으로 시작점을 정한 뒤,
    rglob("패턴")으로 그 아래를 재귀적으로 검색합니다.

    rglob()의 r은 recursive(재귀적)의 뜻입니다.
    즉, 한 단계만 보지 않고 안쪽 폴더까지 계속 들어갑니다.

패턴 예시:
    "*.txt"  → 이름이 .txt로 끝나는 파일만
    "*.py"   → 파이썬 파일만
    "*"      → 파일과 폴더를 가리지 않고 모두

아래 예제들은 연습용으로 삼중 따옴표로 감싸 두었습니다.
실행하고 싶은 부분만 삼중 따옴표를 지우고 돌려 보세요.
"project" 대신 본인 컴퓨터의 폴더 이름을 넣어야 합니다.
"""

# ============================================================
# pathlib 사용 — 모든 .txt 파일 찾기
# ============================================================
# Path("project") : "project"라는 폴더를 시작점으로 잡습니다.
# rglob("*.txt")  : 그 폴더와 하위 폴더에서 .txt 파일만 찾습니다.
#
# for 문으로 하나씩 꺼내 print()하면 경로가 출력됩니다.
# 독일어 텍스트 파일을 모을 때도 같은 방식으로 쓸 수 있습니다.

"""
from pathlib import Path

path = Path("project")  # "project" 대신 본인의 폴더명을 입력해 보세요.

# ".txt" 대신 찾고 싶은 확장자를 넣으면 됩니다. 예: "*.csv", "*.md"
for file in path.rglob("*.txt"):
    print(file)  # 찾은 파일의 경로를 출력합니다.
"""

# ============================================================
# 모든 항목 찾기  (파일 + 폴더)
# ============================================================
# "*" 는 "무엇이든 다"라는 뜻입니다.
# 그래서 파일과 폴더가 모두 출력됩니다.
# 종류를 가리지 않고 무엇이 있는지 한눈에 보고 싶을 때 씁니다.

"""
from pathlib import Path

path = Path("project")  # "project" 대신 본인의 폴더명을 입력해 보세요.

# rglob("*") : 확장자 제한 없이, 파일과 폴더를 모두 찾습니다.
for item in path.rglob("*"):
    print(item)
"""

# ============================================================
# 파일만 찾기
# ============================================================
# rglob("*")는 파일과 폴더를 함께 줍니다.
# 그중 파일만 남기려면 is_file()로 확인합니다.
#
#   item.is_file() → 파일이면 True, 아니면 False
# True인 것만 print하면 "파일만" 볼 수 있습니다.

"""
from pathlib import Path

path = Path("project")  # "project" 대신 본인의 폴더명을 입력해 보세요.

for item in path.rglob("*"):
    # is_file() : 이 항목이 파일인지 확인합니다. (폴더는 False)
    if item.is_file():
        print("파일:", item)
"""

# ============================================================
# 폴더만 찾기
# ============================================================
# 이번엔 폴더만 보고 싶을 때입니다.
# is_dir()은 directory(디렉토리, 즉 폴더)인지 물어봅니다.
#
#   item.is_dir() → 폴더이면 True, 파일이면 False

"""
from pathlib import Path

path = Path("project")  # "project" 대신 본인의 폴더명을 입력해 보세요.

for item in path.rglob("*"):
    # is_dir() : 이 항목이 폴더인지 확인합니다. (파일은 False)
    if item.is_dir():
        print("폴더:", item)
"""

# ============================================================
# 예제 1: .py 파일 개수 세기
# ============================================================
# 파일을 찾기만 하지 않고, 몇 개인지도 셀 수 있습니다.
#
# 방법:
#   1) count를 0으로 시작합니다.
#   2) .py 파일을 하나 찾을 때마다 count에 1을 더합니다.
#   3) 반복이 끝나면 count가 전체 개수입니다.

"""
from pathlib import Path

path = Path("project")  # "project" 대신 본인의 폴더명을 입력해 보세요.

count = 0  # 아직 하나도 세지 않았으므로 0부터 시작합니다.

for file in path.rglob("*.py"):  # 파이썬 파일만 대상으로
    count += 1  # 파일을 하나 찾을 때마다 1씩 증가 (count = count + 1)

print("파이썬 파일 수:", count)
"""

# ============================================================
# 예제 2: 특정 키워드가 포함된 파일 찾기
# ============================================================
# 파일 이름에 어떤 단어가 들어 있는지만 골라 보고 싶을 때 씁니다.
# 예: 이름에 "report"가 들어간 파일만 찾기
#
#   file.name          → 경로가 아니라 파일 이름만 (예: "final_report.txt")
#   "report" in 이름   → 이름 안에 "report"라는 글자가 있으면 True
#
# is_file()도 함께 확인하는 이유:
#   폴더 이름에 "report"가 있어도 제외하고, 파일만 출력하기 위해서입니다.

"""
from pathlib import Path

path = Path("project")  # "project" 대신 본인의 폴더명을 입력해 보세요.

for file in path.rglob("*"):
    # 파일이고, 이름에 "report"가 들어 있으면 출력합니다.
    # "report" 대신 다른 키워드(예: "klausur", "übung")를 넣어도 됩니다.
    if file.is_file() and "report" in file.name:
        print(file)
"""

# ============================================================
# 예제 3: 빈 폴더 찾기
# ============================================================
# 빈 폴더 = 안에 파일도 없고 하위 폴더도 없는 폴더
#
# folder.iterdir() :
#     그 폴더 바로 안에 있는 항목들을 하나씩 꺼냅니다.
#     (rglob과 달리, 더 깊은 하위 폴더까지는 들어가지 않습니다.)
#
# any(...) :
#     안에 항목이 하나라도 있으면 True, 아무것도 없으면 False
#
# not any(folder.iterdir()) :
#     "안에 아무것도 없다" → 빈 폴더입니다.

"""
from pathlib import Path

path = Path("project")  # "project" 대신 본인의 폴더명을 입력해 보세요.

for folder in path.rglob("*"):
    if folder.is_dir():  # 폴더인 경우만 검사합니다.
        if not any(folder.iterdir()):
            print("빈 폴더:", folder)
"""
