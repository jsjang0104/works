"""
로또 번호 생성

1~45 사이 중복 없는 6개 숫자를 무작위로 뽑아 5세트 출력합니다.

이 예제에서 익히는 것:
    - import : 미리 만들어 둔 도구(모듈)를 불러오기
    - random.sample() : 여러 개 중에서 중복 없이 뽑기
    - range() : 연속된 숫자 범위를 만들기
    - for : 같은 일을 여러 번 반복하기
    - sort() : 작은 수부터 큰 수 순서로 정렬하기
"""

# random 모듈을 불러옵니다.
# 모듈 = 필요할 때 꺼내 쓰는 전용 도구 상자
# random 안에는 무작위로 값을 뽑는 함수들이 들어 있습니다.
import random

print("===== 로또 번호 5세트 =====")

# range(5)는 0, 1, 2, 3, 4 를 만듭니다. 즉 5번 반복합니다.
# i는 반복할 때마다 0 → 1 → 2 → 3 → 4 로 바뀝니다.
for i in range(5):
    # random.sample(모음, 개수)
    #   모음에서 개수만큼 값을 뽑되, 같은 값은 두 번 나오지 않습니다.
    #
    # range(1, 46) 은 1부터 45까지입니다.
    #   끝 숫자 46은 포함되지 않습니다. (1 이상, 46 미만)
    #   그래서 로또 번호 1~45를 이렇게 만듭니다.
    numbers = random.sample(range(1, 46), 6)

    # sort()는 리스트를 작은 수부터 큰 수 순서로 바꿉니다.
    # 예: [32, 7, 41, 3, 18, 25] → [3, 7, 18, 25, 32, 41]
    numbers.sort()

    # f-문자열: 중괄호 {} 안에 변수를 넣으면 그 값이 출력됩니다.
    # i는 0부터 시작하므로, 사람에게 보이는 세트 번호는 i + 1 로 만듭니다.
    #   i=0 → 1세트, i=1 → 2세트, ...
    print(f"{i + 1}세트: {numbers}")
