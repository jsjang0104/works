"""
Python 예외 처리

예외(exception)는 프로그램이 실행되는 도중에 발생하는 '예상 밖의 오류'입니다.
예외를 처리하지 않으면 프로그램이 그 자리에서 멈춰 버립니다.

예외 처리(exception handling)는 오류가 나도 프로그램이 바로 죽지 않고,
미리 정해 둔 안내 메시지를 보여 주거나 다른 일을 하게 하는 방법입니다.

비유:
    예외     = 길을 가다가 갑자기 구멍에 빠지는 일
    try      = "이 길을 조심히 가 보자"
    except   = "구멍에 빠지면 이렇게 대처하자"
    else     = "구멍에 안 빠졌으면 계속 가던 길을 가자"
    finally  = "구멍에 빠지든 안 빠지든, 마지막에 꼭 할 일"

기본 구조:
    try:
        오류가 날 수도 있는 코드
    except 예외이름:
        그 오류가 났을 때 실행할 코드

아래 예제들은 연습용으로 삼중 따옴표로 감싸 두었습니다.
실행하고 싶은 부분만 삼중 따옴표를 지우고 돌려 보세요.
"""

# ============================================================
# 예외 1: ZeroDivisionError  (0으로 나누기)
# ============================================================
# 어떤 숫자를 0으로 나누면 수학적으로 결과가 없습니다.
# Python은 이때 ZeroDivisionError를 발생시킵니다.
# 예: 10 / 0  → 오류

"""
try:
    # input() : 키보드로 글자를 입력받습니다. 결과는 항상 문자열(str)입니다.
    # int()   : 그 문자열을 정수로 바꿉니다. 예: "3" → 3
    num = int(input("숫자를 입력하세요: "))
    print(10 / num)   # num이 0이면 여기서 오류가 납니다.
except ZeroDivisionError:
    # 0으로 나눈 경우에만 이 메시지가 출력됩니다.
    print("0으로 나눌 수 없습니다.")
"""

# ============================================================
# 예외 2: ValueError  (값이 잘못된 경우)
# ============================================================
# int()는 "123"처럼 숫자로 된 문자열만 정수로 바꿀 수 있습니다.
# "안녕"처럼 숫자가 아닌 글자를 넣으면 ValueError가 발생합니다.
# 예: int("hello")  → 오류

"""
try:
    num = int(input("숫자를 입력하세요: "))  # "abc"를 입력하면 오류
    print(num)
except ValueError:
    # 정수로 바꿀 수 없는 값을 입력한 경우에만 실행됩니다.
    print("정수를 입력해야 합니다.")
"""

# ============================================================
# 예외 3: IndexError  (리스트 범위를 벗어난 경우)
# ============================================================
# 리스트의 칸 번호(인덱스)는 0부터 시작합니다.
# numbers = [1, 2, 3] 이면
#   numbers[0] → 1
#   numbers[1] → 2
#   numbers[2] → 3
#   numbers[5] → 없는 칸이므로 IndexError

"""
numbers = [1, 2, 3]   # 칸은 0, 1, 2번까지 있습니다.
try:
    print(numbers[5])  # 5번 칸은 없으므로 오류가 납니다.
except IndexError:
    print("리스트 범위를 벗어났습니다.")
"""

# ============================================================
# 예외 4: FileNotFoundError  (파일이 없는 경우)
# ============================================================
# open("파일명", "r") : 파일을 읽기(read) 모드로 엽니다.
# 그 파일이 컴퓨터에 없으면 FileNotFoundError가 발생합니다.

"""
try:
    file = open("sample.txt", "r")  # sample.txt가 없으면 오류
except FileNotFoundError:
    print("파일을 찾을 수 없습니다.")
"""

# ============================================================
# 예외 5: TypeError  (타입이 맞지 않는 경우)
# ============================================================
# Python에서 + 는 같은 종류의 값끼리만 잘 동작합니다.
# "10"은 문자열(str), 5는 정수(int)라서 서로 더할 수 없습니다.
# 예: "10" + 5  → TypeError
# 참고: "10" + "5"는 "105"가 되고, 10 + 5는 15가 됩니다.

"""
try:
    result = "10" + 5  # 문자열과 숫자는 바로 더할 수 없습니다.
except TypeError:
    print("문자열과 숫자는 직접 더할 수 없습니다.")
"""

# ============================================================
# 여러 개의 예외 처리하기
# ============================================================
# try 안에는 여러 종류의 오류가 날 수 있습니다.
# except를 여러 개 적으면, 실제로 난 오류에 맞는 쪽만 실행됩니다.
#
# 이 예제에서 가능한 오류:
#   ValueError         → 숫자가 아닌 글자를 입력한 경우
#   ZeroDivisionError  → 0을 입력해서 10을 0으로 나눈 경우
#
# 위에서부터 차례로 확인하므로, 해당하는 except가 실행되면
# 그 아래 except는 건너뜁니다.

"""
try:
    num = int(input("숫자를 입력하세요: "))  # 여기서 ValueError 가능
    print(10 / num)                          # 여기서 ZeroDivisionError 가능
except ValueError:
    print("숫자를 올바르게 입력하세요.")
except ZeroDivisionError:
    print("0으로 나눌 수 없습니다.")
"""

# ============================================================
# 예외 객체 받기: as
# ============================================================
# except 예외이름 as 변수이름:
#   → 발생한 오류의 자세한 내용을 변수에 담아 볼 수 있습니다.
# 보통 e 또는 err 같은 짧은 이름을 씁니다.
# print(e)를 하면 Python이 알려 주는 원래 오류 메시지가 나옵니다.

"""
try:
    num = int("hello")  # "hello"는 숫자가 아니라서 ValueError
except ValueError as e:
    # e 안에는 "invalid literal for int() with base 10: 'hello'" 같은
    # Python의 원래 오류 설명이 들어 있습니다.
    print("예외가 발생했습니다.")
    print("오류 메시지:", e)
"""

# ============================================================
# else 구문
# ============================================================
# else는 try 안에서 예외가 하나도 나지 않았을 때만 실행됩니다.
# 오류가 났으면 except만 실행되고, else는 건너뜁니다.
#
# 쓰는 이유:
#   "입력이 성공했을 때만" 하고 싶은 일을 else에 두면
#   성공/실패가 코드에서 분명하게 나뉩니다.

"""
try:
    num = int(input("숫자를 입력하세요: "))  # 성공하면 num에 숫자가 저장됩니다.
except ValueError:
    print("숫자를 입력해야 합니다.")
else:
    # 여기까지 왔다는 것은 변환이 성공했다는 뜻입니다.
    print("입력한 숫자는", num, "입니다.")
"""

# ============================================================
# finally 구문
# ============================================================
# finally는 예외가 나든 안 나든, 맨 마지막에 항상 실행됩니다.
# 파일을 닫거나, "작업이 끝났습니다"처럼 마무리 안내를 할 때 자주 씁니다.
#
# 실행 순서 정리:
#   1) try를 실행한다
#   2) 오류가 나면 except를 실행한다 (없으면 건너뜀)
#   3) 오류가 없으면 else를 실행한다 (있으면)
#   4) finally는 언제나 실행한다

"""
try:
    f = open("data.txt", "r")  # 파일이 없으면 여기서 오류
    content = f.read()          # 파일이 있으면 내용을 읽습니다.
except FileNotFoundError:
    print("파일이 존재하지 않습니다.")
finally:
    # 파일이 있든 없든, 이 줄은 반드시 출력됩니다.
    print("작업이 종료되었습니다.")
"""
